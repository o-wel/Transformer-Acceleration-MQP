"""Build paper tables from preserved measurements; standard library only."""
from pathlib import Path
from collections import Counter
import csv
import hashlib
import json
import statistics as stats

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
BASE = REPO / 'transformer_syed/minGPT/experiments'
MATCH = BASE / 'flash_attention/results/fp16_hyperparameter_search/runs/20261111_fp16_matched'
MATRIX = BASE / 'optimization_matrix/runs/20261112_full_matrix'
hashes = {}

def read(path):
    raw = path.read_bytes()
    hashes[str(path.relative_to(REPO))] = hashlib.sha256(raw).hexdigest()
    return json.loads(raw)

def records(root, pattern):
    return [row for path in sorted(root.glob(pattern)) for row in read(path)]

quality = []
coverage = []
for task in ['basketball', 'spam']:
    for precision in ['fp32', 'fp16']:
        name = f'{task}_{precision}'
        root = MATCH / ('fp32_basketball_reference' if name == 'basketball_fp32' else name)
        cells = records(root, 'systems-*.json')
        assert len(cells) == 1440
        assert all(len(c['samples']) == 7 for c in cells)
        counts = Counter(c['status'] for c in cells)
        assert set(counts) <= {'ok', 'parity_failed'}
        coverage.append(dict(study='matched', task=task, precision=precision,
                             total=len(cells), passed=counts['ok'], failed=counts['parity_failed']))
        for method in ['lora', 'full']:
            rows = read(root / f'{method}-test.json')
            assert sorted(r['seed'] for r in rows) == [42, 43, 44]
            metrics = ['fields_correct'] if task == 'basketball' else ['accuracy', 'spam_f1']
            for metric in metrics:
                vals = [r['metrics'][metric] for r in rows]
                quality.append(dict(task=task, precision=precision, method=method, metric=metric,
                                    mean_percent=100*stats.mean(vals), seed_sd_percent=100*stats.stdev(vals)))
        root = MATRIX / name
        confirmation = records(root, 'confirmation-*.json')
        calibration = records(root, 'calibration-*.json')
        natural = records(root, 'quality-*.json')
        assert (len(calibration), len(confirmation), len(natural)) == (2592, 2232, 93)
        assert all(len(c['samples']) == 7 for c in confirmation)
        assert len({(json.dumps(c['state'], sort_keys=True), c['seed']) for c in natural}) == 93
        assert {c['seed'] for c in natural} == {42, 43, 44}
        counts = Counter(c['status'] for c in confirmation)
        assert set(counts) <= {'ok', 'parity_failed'}
        coverage.append(dict(study='matrix', task=task, precision=precision,
                             total=len(confirmation), passed=counts['ok'], failed=counts['parity_failed']))

for filename, rows in [('PRECISION_QUALITY.csv', quality), ('PRECISION_COVERAGE.csv', coverage)]:
    with (HERE / filename).open('w') as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
(HERE / 'PRECISION_EVIDENCE.json').write_text(json.dumps(dict(input_sha256=hashes, quality=quality, coverage=coverage), indent=2)+'\n')

tex = r'''% Generated by build_precision_evidence.py; do not edit numeric tables manually.
\section{Matched Precision Results}
\label{sec:precision_results}
The matched extension evaluates FP16 mixed precision alongside the primary FP32 study. Linear projections, attention operands and outputs, and KV caches use FP16; master parameters, gradients, AdamW state, stable reductions, and attention accumulators retain FP32. TF32 remains disabled. GradScaler starts at 128, and nonfinite or skipped updates fail the training trial. This policy is not pure FP16 storage or arithmetic.

Both tasks use the staged 90-configuration screen, 1,200-example screening budget, 9,600-example refinement budget, validation-only selection, and confirmation seeds 42, 43, and 44. The SMS extension includes a new matched FP32 sweep; the earlier two-learning-rate SMS experiment is a separate study. Each newly run task/precision study completed 126 training trials. The historical FP32 basketball study is retained as the precision reference.

\subsection{Held-out quality}
Table~\ref{tab:precision_quality} reports independently selected LoRA configurations. These comparisons include configuration and training-policy differences; they do not isolate a fixed-weight casting effect. SMS evaluation uses 771 held-out messages, including 93 spam messages, from the existing split. Basketball uses 120 questions from 40 matches. Standard deviations describe three training seeds sharing one test set and are not confidence intervals or evidence of statistical equivalence.

\begin{table}[htbp]
\centering
\begin{tabular}{lrr}
\toprule
LoRA task metric (\%) & FP32 & FP16 mixed\\
\midrule
'''
labels = [('basketball', 'fields_correct', 'Basketball fields correct'), ('spam', 'accuracy', 'SMS accuracy'), ('spam', 'spam_f1', 'SMS spam F1')]
for task, metric, label in labels:
    values = []
    for precision in ['fp32', 'fp16']:
        row = next(r for r in quality if (r['task'],r['metric'],r['precision'],r['method']) == (task,metric,precision,'lora'))
        values.append(f"${row['mean_percent']:.2f} \\pm {row['seed_sd_percent']:.2f}$")
    tex += label + ' & ' + ' & '.join(values) + r'\\' + '\n'
tex += r'''\bottomrule
\end{tabular}
\caption{Mean and sample standard deviation across three training seeds for independently tuned LoRA winners.}
\label{tab:precision_quality}
\end{table}

\subsection{Numerical acceptance and ablation coverage}
Serving acceptance requires both logit agreement with absolute and relative tolerances of $3\times10^{-4}$ and exact complete greedy-token parity with the same checkpoint using eager attention without caching. These are within-precision execution checks, not cross-checkpoint or cross-precision equality requirements. Passing FP16 kernel preflight with its separately declared diagnostic tolerance does not establish serving acceptance.

\begin{table}[htbp]
\centering
\begin{tabular}{llrr}
\toprule
Study & Task & FP32 passing & FP16 passing\\
\midrule
'''
for study, label in [('matched','Matched search'), ('matrix','Ablation confirmation')]:
    for task in ['basketball','spam']:
        vals = [next(r for r in coverage if (r['study'],r['task'],r['precision']) == (study,task,p)) for p in ['fp32','fp16']]
        tex += f"{label} & {task.capitalize()} & " + ' & '.join(f"{v['passed']}/{v['total']}" for v in vals) + r'\\'+'\n'
tex += r'''\bottomrule
\end{tabular}
\caption{Serving acceptance counts. Coverage completion does not imply numerical acceptance.}
\label{tab:precision_coverage}
\end{table}

All custom-attention and hybrid cells in the matched FP16 systems study fail the strict gate; their timings remain diagnostic and cannot support output-preserving acceleration claims. Some eager cached basketball cells also fail. The FP32 comparison passes throughout the measured grid. These failures establish a limitation under the declared gate; they do not alone establish the cause of the differences or a loss of task accuracy.

A subsequent ablation study adds 27 off/best-observed/poor-observed states and four joint serving selections for each task/precision. It freezes prior validation-based training choices, retrains nine models (three choices by three seeds), calibrates serving choices on a separate prompt stream from confirmation, randomizes case order, and records 2,592 calibration, 2,232 confirmation, and 93 natural-task quality records per task/precision. Confirmation uses two warmups and seven measured repetitions. LoRA off denotes the full-fine-tuning control; attention and cache are serving factors. SMS classification predicts one label and does not itself demonstrate autoregressive cache acceleration. Synthetic serving workloads and natural task quality are reported separately.

The measured training-quality and ablation findings can therefore be reported alongside the numerical failures. Cross-precision equivalence, universally beneficial combined acceleration, and preservation by every FP16 backend are not established. Reused splits, unequal full-versus-LoRA tuning effort, and timing repetitions within allocations limit generalization. Independent allocation repeats and a newly frozen evaluation set would strengthen broader claims.
'''
(HERE / 'PRECISION_RESULTS.tex').write_text(tex)
print(f'Verified {len(hashes)} raw inputs; wrote quality, coverage, provenance and LaTeX tables.')
